import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import test from "node:test";
import { extensionIdFromKey, parseJsonc, renderProdConfig } from "./setup.mjs";

const root = join(import.meta.dirname, "..");
const PINNED_ID = "cijkjhifndknmohbpoohohhialjdkoji";

test("pinned extension key maps to the expected Chrome ID", () => {
  const config = readFileSync(join(root, "apps/extension/wxt.config.ts"), "utf8");
  const key = config.match(/\n\s*key:\s*"([^"]+)"/)?.[1];
  assert.ok(key, "wxt.config.ts should contain a manifest key");
  assert.equal(extensionIdFromKey(key), PINNED_ID);
});

test("parseJsonc drops comments and trailing commas", () => {
  const parsed = parseJsonc(`{
    // line comment
    "name": "demo", /* block comment */
    "list": [1, 2,],
  }`);
  assert.deepEqual(parsed, { name: "demo", list: [1, 2] });
});

test("renderProdConfig writes the values collected by setup", () => {
  const text = renderProdConfig({
    workerName: "demo-worker",
    cfAccountId: "acct_123",
    databaseId: "db_123",
    publicUrl: "https://demo.example.workers.dev",
    googleClientId: "client.apps.googleusercontent.com",
    allowedEmails: "you@example.com",
    extensionId: PINNED_ID,
  });
  assert.match(text, /Generated by scripts\/setup\.mjs/);
  assert.match(text, /"account_id": "acct_123"/);
  assert.match(text, /"database_id": "db_123"/);
  assert.match(text, /"PUBLIC_URL": "https:\/\/demo\.example\.workers\.dev"/);
  assert.match(text, /"ALLOWED_EXTENSION_IDS": "cijkjhifndknmohbpoohohhialjdkoji"/);
});
