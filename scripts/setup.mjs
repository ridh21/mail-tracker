/** Parse JSONC: drop comments outside strings and trailing commas. */
export function parseJsonc(text) {
  let out = "";
  let inString = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    const n = text[i + 1];
    if (inString) {
      out += c;
      if (c === "\\") out += text[++i] ?? "";
      else if (c === '"') inString = false;
    } else if (c === '"') {
      inString = true;
      out += c;
    } else if (c === "/" && n === "/") {
      while (i < text.length && text[i] !== "\n") i++;
      out += "\n";
    } else if (c === "/" && n === "*") {
      i += 2;
      while (i < text.length && !(text[i] === "*" && text[i + 1] === "/")) i++;
      i++;
    } else out += c;
  }
  return JSON.parse(out.replace(/,(\s*[}\]])/g, "$1"));
}

function setString(text, key, val) {
  const re = new RegExp(`("${key}"\\s*:\\s*)"(?:[^"\\\\]|\\\\.)*"`);
  if (!re.test(text)) throw new Error(`"${key}" not found in apps/worker/wrangler.jsonc`);
  return text.replace(re, (_, prefix) => `${prefix}${JSON.stringify(val)}`);
}

/** Values already deployed by hand, so a re-run (or an older setup) is picked up. */
function readExistingDeployment() {
  if (!existsSync(PROD_CONFIG)) return {};
  try {
    const cfg = parseJsonc(readFileSync(PROD_CONFIG, "utf8"));
    const vars = cfg.vars ?? {};
    const topic = vars.GMAIL_PUBSUB_TOPIC || "";
    return {
      cfAccountId: cfg.account_id,
      workerName: cfg.name,
      databaseId: cfg.d1_databases?.[0]?.database_id,
      publicUrl: vars.PUBLIC_URL && vars.PUBLIC_URL !== LOCAL_URL ? vars.PUBLIC_URL : undefined,
      googleClientId: vars.GOOGLE_CLIENT_ID || undefined,
      gcpProject: topic.split("/")[1] || undefined,
      pubsub: topic ? { topic, serviceAccount: vars.PUBSUB_SERVICE_ACCOUNT } : undefined,
      allowedEmails: vars.ALLOWED_EMAILS || undefined,
    };
  } catch {
    return {};
  }
}

/**
 * Write the gitignored production config from the committed template, so the real
 * values never land in git and template changes flow through on every run.
 */
export function renderProdConfig(state) {
  let text = readFileSync(BASE_CONFIG, "utf8");
  text = text.replace(/^(\s*"name"\s*:\s*)"[^"]*"/m, (_, prefix) => `${prefix}${JSON.stringify(state.workerName)}`);
  text = text.replace(
    /^(\s*"name"\s*:\s*"[^"]*",\n)/m,
    (line) => `${line}  "account_id": ${JSON.stringify(state.cfAccountId)},\n`,
  );
  text = setString(text, "database_id", state.databaseId);
  text = setString(text, "PUBLIC_URL", state.publicUrl ?? LOCAL_URL);
  text = setString(text, "GOOGLE_CLIENT_ID", state.googleClientId ?? "");
  text = setString(text, "GMAIL_PUBSUB_TOPIC", state.pubsub?.topic ?? "");
  text = setString(text, "PUBSUB_SERVICE_ACCOUNT", state.pubsub?.serviceAccount ?? "");
  text = setString(text, "ALLOWED_EMAILS", state.allowedEmails ?? "");
  text = setString(text, "ALLOWED_EXTENSION_IDS", state.extensionId ?? "");
  const header = `// ${GENERATED_MARK} from wrangler.jsonc. Real deployment values; gitignored.\n// Re-run ./setup.sh to change them, or edit and deploy with \`pnpm run deploy:prod\`.\n`;
  return header + text;
}

function writeProdConfig(state) {
  const text = renderProdConfig(state);
  if (DRY_RUN) return;
  if (existsSync(PROD_CONFIG) && !readFileSync(PROD_CONFIG, "utf8").includes(GENERATED_MARK)) {
    copyFileSync(PROD_CONFIG, PROD_BACKUP);
    p.log.info(`Your hand-written ${PROD_CONFIG_NAME} was backed up to ${relative(ROOT, PROD_BACKUP)}.`);
  }
  writeFileSync(PROD_CONFIG, text);
}

export function extensionIdFromKey(publicKeyBase64) {
  const hex = createHash("sha256").update(Buffer.from(publicKeyBase64, "base64")).digest("hex").slice(0, 32);
  return [...hex].map((c) => String.fromCharCode(97 + parseInt(c, 16))).join("");
}

