async function main() {
  console.clear();
  p.intro(`${pc.bgBlue(pc.white(" ✓✓ Mail Tracker "))} ${pc.dim("self-hosting setup")}${DRY_RUN ? pc.yellow("  [dry run: nothing will change]") : ""}`);

  const state = { ...readExistingDeployment(), ...loadState() };
  const resuming = Object.keys(state).length > 0;

  p.note(
    [
      `${pc.bold("What this sets up")}`,
      `  Your own Mail Tracker on ${pc.bold("your")} Cloudflare and Google accounts.`,
      `  Nothing is shared with anyone else. Takes about ${pc.bold("10 minutes")}.`,
      "",
      `${pc.bold("You'll need")}`,
      "  • A Cloudflare account (free) and a Google account",
      "  • Chrome, for the extension",
      "",
      `${pc.bold("How it works")}`,
      `  ${tag.auto} steps run on their own. Just wait.`,
      `  ${tag.you} steps need you. You'll get a numbered checklist`,
      "  with every value to copy, and the page opens for you.",
      "",
      ...STEPS.map((s, i) => `  ${pc.dim(String(i + 1).padStart(2))}  ${s.title}`),
    ].join("\n"),
    "Before you start",
  );

  if (resuming) {
    p.log.info(`Found a previous setup${state.publicUrl ? ` for ${link(state.publicUrl)}` : ""}. Finished parts are reused, and your keys are kept.`);
  }
  await proceed("Ready to begin?", "Let's go");

  await stepCloudflare(state);
  await stepDatabase(state);
  await stepKeys(state);
  await stepGoogle(state);
  await stepPubsub(state);
  await stepOauth(state);
  await stepAccess(state);
  await stepExtension(state);
  await stepDeploy(state);

  const extPath = EXT_OUTPUT;
  p.note(
    [
      `${pc.dim("Dashboard")}   ${link(state.publicUrl)}`,
      `${pc.dim("Google")}      project ${value(state.gcpProject)}`,
      `${pc.dim("Replies")}     ${state.pubsub ? "instant (Pub/Sub)" : "hourly"}`,
      `${pc.dim("Access")}      ${state.allowedEmails}`,
      `${pc.dim("Extension")}   ${extPath}`,
    ].join("\n"),
    DRY_RUN ? pc.yellow("Dry run complete: this is what you'd get") : pc.green("Your Mail Tracker is deployed"),
  );

  p.log.step(`${pc.bold("Last step: install the extension")}  ${tag.you}`);
  checklist("In Chrome", [
    `Go to ${code("chrome://extensions")}.`,
    `Turn on ${value("Developer mode")} (top right).`,
    `Click ${value("Load unpacked")} and choose this folder:\n   ${code(extPath)}`,
    aside("Already had it loaded? Remove it first, then load it again. Its ID is now fixed, so you'll reconnect once."),
    `Click the Mail Tracker icon in the toolbar, then ${value("Connect")}. Sign in with ${code(state.allowedEmails.split(",")[0])} and allow Gmail read access.`,
    "Reload Gmail and send yourself an email. A tick appears at once and turns blue when it's opened.",
    ...(state.pubsub ? [`In the dashboard, open ${value("Settings")} and click ${value("Sync now")} to switch on instant reply sync.`] : []),
  ]);

  if (process.platform === "darwin" && !DRY_RUN) {
    const copy = guard(await p.confirm({ message: "Copy the extension folder path to your clipboard?", initialValue: true }));
    if (copy) {
      exec("pbcopy", [], { input: extPath });
      p.log.success("Copied. Paste it into the Load unpacked dialog with ⌘⇧G, then ⌘V.");
    }
  }

  p.outro(
    DRY_RUN
      ? `Nothing was created or changed. Run ${code("./setup.sh")} without --dry-run to set it up for real.`
      : `Done. Run ${code("./setup.sh")} again any time to change settings. Your keys are kept.`,
  );
}

