/** Run quietly and capture output. */
function exec(cmd, args, { cwd = ROOT, env, input } = {}) {
  const res = spawnSync(cmd, args, {
    cwd,
    input,
    encoding: "utf8",
    env: { ...process.env, ...env },
    stdio: ["pipe", "pipe", "pipe"],
  });
  return { code: res.status ?? 1, stdout: res.stdout ?? "", out: `${res.stdout ?? ""}${res.stderr ?? ""}` };
}

/** Hand the terminal to a command that needs you (browser sign-ins). */
function interactive(cmd, args, { cwd = ROOT, env } = {}) {
  const res = spawnSync(cmd, args, { cwd, env: { ...process.env, ...env }, stdio: "inherit" });
  return res.status ?? 1;
}

/** Run with a live, collapsing log; the log stays visible only if it fails. */
function task(title, cmd, args, { cwd = ROOT, env } = {}) {
  if (DRY_RUN) {
    p.log.info(`${pc.dim("[dry run] would run:")} ${cmd === WRANGLER ? "wrangler" : cmd} ${args.join(" ")}`);
    return Promise.resolve({ code: 0, out: "" });
  }
  const log = p.taskLog({ title, limit: 6 });
  return new Promise((resolve) => {
    const child = spawn(cmd, args, { cwd, env: { ...process.env, ...env }, stdio: ["inherit", "pipe", "pipe"] });
    let out = "";
    const onData = (chunk) => {
      const text = chunk.toString();
      out += text;
      for (const line of text.split(/\r?\n/)) {
        // eslint-disable-next-line no-control-regex
        const clean = line.replace(/\u001b\[[0-9;]*[A-Za-z]/g, "").trimEnd();
        if (clean) log.message(clean);
      }
    };
    child.stdout.on("data", onData);
    child.stderr.on("data", onData);
    child.on("close", (code) => {
      if (code === 0) log.success(title);
      else log.error(`${title} failed`);
      resolve({ code: code ?? 1, out });
    });
  });
}

/** A short quiet operation behind a spinner. */
function quietly(message, fn) {
  const s = p.spinner();
  s.start(message);
  try {
    const result = fn();
    s.stop(message.replace(/…$/, ""));
    return result;
  } catch (error) {
    s.error(message.replace(/…$/, ""));
    throw error;
  }
}

function wrangler(args, opts = {}) {
  return exec(WRANGLER, args, { cwd: WORKER_DIR, ...opts, env: { ...wranglerEnv, ...opts.env } });
}
let wranglerEnv = {};

function gcloud(args, opts) {
  return exec("gcloud", [...args, "--quiet"], opts);
}

function openUrl(url) {
  const cmd = process.platform === "darwin" ? "open" : process.platform === "win32" ? "cmd" : "xdg-open";
  const args = process.platform === "win32" ? ["/c", "start", "", url] : [url];
  try {
    spawn(cmd, args, { stdio: "ignore", detached: true }).unref();
  } catch {
    // Opening is a convenience; the link is printed either way.
  }
}

/** Offer to open a page, then wait until you say you're done with it. */
async function visit(url, doneMessage) {
  p.log.message(`${pc.dim("Page:")} ${link(url)}`);
  const open = guard(
    await p.select({
      message: "Open this page in your browser?",
      options: [
        { value: "open", label: "Open it for me" },
        { value: "self", label: "I'll open the link myself" },
      ],
    }),
  );
  if (open === "open") openUrl(url);
  for (;;) {
    const done = guard(await p.confirm({ message: doneMessage, active: "Done", inactive: "Not yet", initialValue: true }));
    if (done) return;
    p.log.message(pc.dim("No rush. Finish the page, then answer Done. The link again: ") + link(url));
  }
}

