/** Step banner: where you are, and whether you need to do anything. */
function step(id, mode, summary) {
  const index = STEPS.findIndex((s) => s.id === id) + 1;
  const counter = pc.dim(`Step ${index} of ${STEPS.length}`);
  p.log.step(`${counter}  ${pc.bold(STEPS[index - 1].title)}  ${tag[mode]}`);
  if (summary) p.log.message(pc.dim(summary));
}

// eslint-disable-next-line no-control-regex
const visible = (text) => text.replace(/\u001b\[[0-9;]*m/g, "");

/** Word-wrap to the terminal, measuring visible width and keeping a hanging indent. */
function wrap(text, indent) {
  const width = Math.max(48, Math.min((process.stdout.columns || 100) - 10, 96));
  return text
    .split("\n")
    .map((paragraph, index) => {
      const lines = [];
      let line = index === 0 ? "" : indent;
      for (const word of paragraph.split(" ")) {
        const candidate = line.trim() ? `${line} ${word}` : `${line}${word}`;
        if (visible(candidate).length > width && line.trim()) {
          lines.push(line);
          line = `${indent}${word}`;
        } else line = candidate;
      }
      lines.push(line);
      return lines.join("\n");
    })
    .join("\n");
}

/** Something to point out without making it a step. */
const aside = (text) => ({ aside: text });

/** A numbered checklist for anything you do by hand in a browser. */
function checklist(title, items) {
  let n = 0;
  const body = items
    .map((item) =>
      typeof item === "object" ? pc.dim(wrap(item.aside, "")) : wrap(`${pc.yellow(`${++n}.`)} ${item}`, "   "),
    )
    .join("\n");
  p.note(body, `${pc.yellow("▸")} ${title}`);
}

/** Report an outcome, worded as a plan during a dry run. */
function done(message, planned) {
  if (DRY_RUN) p.log.info(`${pc.dim("[dry run] would:")} ${planned ?? message}`);
  else p.log.success(message);
}

const value = (v) => pc.cyan(v);
const link = (url) => pc.underline(pc.blue(url));
const code = (v) => pc.bold(pc.cyan(v));

/** Stop cleanly on Ctrl+C or Esc and say how to resume. */
function guard(answer) {
  if (p.isCancel(answer)) {
    p.cancel("Setup paused. Run ./setup.sh again to continue where you left off.");
    process.exit(0);
  }
  return answer;
}

/** A yes/no gate where "no" pauses the setup instead of carrying on half-done. */
async function proceed(message, active = "Continue", inactive = "Not now") {
  const ok = guard(await p.confirm({ message, active, inactive, initialValue: true }));
  if (!ok) {
    p.cancel("Setup paused. Run ./setup.sh again to continue where you left off.");
    process.exit(0);
  }
}

function fail(message, detail) {
  if (detail) p.log.error(detail.trim().split("\n").slice(-15).join("\n"));
  p.cancel(`${message}\nFix the problem above, then run ./setup.sh again. Finished steps are skipped.`);
  process.exit(1);
}

