async function stepCloudflare(state) {
  let who = (() => {
    const res = wrangler(["whoami", "--json"]);
    try {
      return res.code === 0 ? JSON.parse(res.stdout) : null;
    } catch {
      return null;
    }
  })();

  if (who?.loggedIn) {
    step("cloudflare", "auto", "You're already signed in to Cloudflare, so this is quick.");
  } else {
    step("cloudflare", "you", "Mail Tracker runs on your own Cloudflare account. The free plan is enough.");
    checklist("Sign in to Cloudflare", [
      "A browser window opens on Cloudflare's sign-in page.",
      `Log in, or create a free account at ${link("https://dash.cloudflare.com/sign-up")}.`,
      `Click ${value("Allow")} to let Wrangler (Cloudflare's CLI) manage Workers for you.`,
      "Come back to this terminal. It continues on its own.",
    ]);
    await proceed("Ready to open Cloudflare sign-in?", "Open sign-in");
    if (interactive(WRANGLER, ["login"], { cwd: WORKER_DIR }) !== 0) fail("Cloudflare sign-in did not finish.");
    const res = wrangler(["whoami", "--json"]);
    who = res.code === 0 ? JSON.parse(res.stdout) : null;
    if (!who?.loggedIn) fail("Still not signed in to Cloudflare.", res.out);
  }
  p.log.success(`Signed in to Cloudflare as ${value(who.email ?? "your account")}`);

  const accounts = who.accounts ?? [];
  if (!accounts.length) fail("This Cloudflare login has no accounts.");
  if (accounts.length === 1) {
    state.cfAccountId = accounts[0].id;
  } else {
    state.cfAccountId = guard(
      await p.select({
        message: "Which Cloudflare account should host Mail Tracker?",
        initialValue: accounts.some((a) => a.id === state.cfAccountId) ? state.cfAccountId : undefined,
        options: accounts.map((a) => ({ value: a.id, label: a.name, hint: a.id })),
      }),
    );
  }
  wranglerEnv = { CLOUDFLARE_ACCOUNT_ID: state.cfAccountId };

  state.workerName = guard(
    await p.text({
      message: "Name for your Worker",
      placeholder: "mail-tracker",
      defaultValue: state.workerName ?? "mail-tracker",
      initialValue: state.workerName ?? "mail-tracker",
      validate: (v) => (/^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?$/.test(v ?? "") ? undefined : "Use lowercase letters, numbers and dashes."),
    }),
  );
  p.log.message(pc.dim(`Your dashboard will live at https://${state.workerName}.<your-subdomain>.workers.dev`));
  saveState(state);
}

async function stepDatabase(state) {
  step("database", "auto", "Creates the database and deploys once to learn your Worker's public URL.");

  const listed = quietly("Looking for your Mail Tracker database…", () => wrangler(["d1", "list", "--json"]));
  if (listed.code !== 0) fail("Could not list your D1 databases.", listed.out);
  let db = JSON.parse(listed.stdout || "[]").find((d) => d.name === DB_NAME);
  if (db) {
    p.log.success(`Using your existing database ${value(DB_NAME)}`);
  } else if (DRY_RUN) {
    p.log.info(`${pc.dim("[dry run] would create D1 database")} ${DB_NAME}`);
    db = { uuid: "00000000-0000-0000-0000-000000000000" };
  } else {
    // Run outside the repo so wrangler can't edit the committed config on its own.
    const scratch = mkdtempSync(join(tmpdir(), "mail-tracker-"));
    const created = quietly(`Creating the ${DB_NAME} database…`, () =>
      exec(WRANGLER, ["d1", "create", DB_NAME], { cwd: scratch, env: wranglerEnv }),
    );
    rmSync(scratch, { recursive: true, force: true });
    if (created.code !== 0) fail("Cloudflare did not create the database.", created.out);
    db = JSON.parse(wrangler(["d1", "list", "--json"]).stdout || "[]").find((d) => d.name === DB_NAME);
    if (!db) fail("The database was created but could not be found afterwards.");
    p.log.success(`Created database ${value(DB_NAME)}`);
  }
  state.databaseId = db.uuid;
  writeProdConfig(state);
  saveState(state);

  if (state.publicUrl) {
    p.log.success(`Your Worker's address: ${link(state.publicUrl)}`);
    return;
  }

  for (;;) {
    const deploy = await deployWorker();
    const url = deploy.out.match(/https:\/\/[a-z0-9-]+\.[a-z0-9-]+\.workers\.dev/)?.[0];
    if (deploy.code === 0 && url) {
      state.publicUrl = url;
      break;
    }
    if (DRY_RUN) {
      state.publicUrl = `https://${state.workerName}.example.workers.dev`;
      break;
    }
    if (/subdomain/i.test(deploy.out)) {
      step("database", "you", "Your Cloudflare account needs a free workers.dev subdomain before the first deploy.");
      checklist("Pick a workers.dev subdomain", [
        `Open ${link(`https://dash.cloudflare.com/${state.cfAccountId}/workers-and-pages`)}.`,
        `Cloudflare asks you to choose a ${value("workers.dev")} subdomain. Pick any name and confirm.`,
        "Come back here and retry.",
      ]);
      await proceed("Subdomain chosen?", "Retry the deploy");
      continue;
    }
    if (deploy.code !== 0) fail("The first deploy failed.", deploy.out);
    state.publicUrl = guard(
      await p.text({
        message: "The deploy worked, but I couldn't read its URL. Paste the https://… address wrangler printed",
        validate: (v) => (/^https:\/\/[^\s/]+$/.test(v ?? "") ? undefined : "Paste the origin only, like https://name.sub.workers.dev"),
      }),
    );
    break;
  }
  writeProdConfig(state);
  saveState(state);
  p.log.success(`Your Worker is live at ${link(state.publicUrl)}`);
}

async function stepKeys() {
  step("keys", "auto", "Two random keys: one encrypts your Google tokens, one signs your sessions. They go straight to Cloudflare and are never shown or saved.");
  const existing = secretNames();
  for (const name of ["TOKEN_ENCRYPTION_KEY", "SESSION_SECRET"]) {
    if (existing.has(name)) {
      p.log.success(`${name} already set, kept as is ${pc.dim("(rotating it would sign everyone out)")}`);
    } else {
      putSecret(name, randomBytes(32).toString("base64"));
      if (!DRY_RUN) p.log.success(`${name} generated and stored`);
    }
  }
}

