/** Build the dashboard, migrate D1, deploy. Returns wrangler's deploy output. */
async function deployWorker() {
  const build = await task("Building the dashboard", "pnpm", ["--filter", "@mail-tracker/dashboard", "build"]);
  if (build.code !== 0) fail("The dashboard did not build.", build.out);
  const migrate = await task("Applying database migrations", WRANGLER, ["d1", "migrations", "apply", DB_NAME, "--remote", "-c", PROD_CONFIG_NAME], {
    cwd: WORKER_DIR,
    env: { ...wranglerEnv, CI: "true" },
  });
  if (migrate.code !== 0) fail("The database migrations did not apply.", migrate.out);
  const deploy = await task("Deploying the Worker to Cloudflare", WRANGLER, ["deploy", "-c", PROD_CONFIG_NAME], {
    cwd: WORKER_DIR,
    env: wranglerEnv,
  });
  return deploy;
}

function secretNames() {
  const res = wrangler(["secret", "list", "--format", "json", "-c", PROD_CONFIG_NAME]);
  if (res.code !== 0) return new Set();
  try {
    return new Set(JSON.parse(res.stdout).map((s) => s.name));
  } catch {
    return new Set();
  }
}

/** Store a Worker secret by piping it to wrangler, so it never touches disk. */
function putSecret(name, secretValue) {
  if (DRY_RUN) {
    p.log.info(`${pc.dim("[dry run] would:")} generate ${name} and store it in Cloudflare`);
    return;
  }
  const res = quietly(`Storing ${name} in Cloudflare…`, () =>
    wrangler(["secret", "put", name, "-c", PROD_CONFIG_NAME], { input: secretValue }),
  );
  if (res.code !== 0) fail(`Cloudflare did not accept ${name}.`, res.out);
}

/**
 * Ask Google whether the client exists and knows the redirect URI. Google answers with
 * a redirect either way: to its sign-in page when all is well, or to an error page
 * whose authError parameter (base64) names the problem.
 */
export async function checkRedirect(clientId, redirectUri) {
  try {
    const params = new URLSearchParams({ client_id: clientId, redirect_uri: redirectUri, response_type: "code", scope: "openid" });
    const res = await fetch(`https://accounts.google.com/o/oauth2/v2/auth?${params}`, { redirect: "manual" });
    let problem = "";
    if (res.status >= 300 && res.status < 400) {
      const location = new URL(res.headers.get("location") ?? "", "https://accounts.google.com");
      if (!location.pathname.includes("/oauth/error")) return "ok";
      const authError = location.searchParams.get("authError") ?? "";
      problem = Buffer.from(authError.replace(/-/g, "+").replace(/_/g, "/"), "base64").toString("latin1");
    } else {
      problem = await res.text();
    }
    if (/redirect_uri_mismatch/.test(problem)) return "redirect";
    if (/invalid_client|deleted_client|was not found/i.test(problem)) return "client";
    return "unknown";
  } catch {
    return "unknown";
  }
}

/** A bogus code tells a valid secret (invalid_grant) from a wrong one (invalid_client). */
export async function checkSecret(clientId, secret, redirectUri) {
  try {
    const res = await fetch("https://oauth2.googleapis.com/token", {
      method: "POST",
      headers: { "content-type": "application/x-www-form-urlencoded" },
      body: new URLSearchParams({ grant_type: "authorization_code", code: "setup-check", client_id: clientId, client_secret: secret, redirect_uri: redirectUri }),
    });
    const json = await res.json().catch(() => ({}));
    if (json.error === "invalid_grant") return "ok";
    if (json.error === "invalid_client" || json.error === "unauthorized_client") return "secret";
    return "unknown";
  } catch {
    return "unknown";
  }
}

